import re
from pathlib import Path
from uuid import uuid4


def safe_name(name):
    name = re.sub(r'[<>:"/\\|?*\x00-\x1f]', '_', name).strip(' .')[:100].rstrip(' .')
    if not name:
        name = 'material'
    if name.split('.')[0].upper() in {'CON', 'PRN', 'AUX', 'NUL', *(f'COM{i}' for i in range(1,10)), *(f'LPT{i}' for i in range(1,10))}:
        name = '_' + name
    return name


def new_output(root, name):
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    for _ in range(10):
        target = root / (safe_name(name) + '_' + uuid4().hex[:10])
        try:
            target.mkdir()
            return target
        except FileExistsError:
            continue
    raise ValueError('Não foi possível criar uma pasta exclusiva.')


def material_pdf(folder, name=None, *, new=False):
    """Resolve the saved material, independent of later review edits.

    Separate exclusive material directories prevent collisions across items;
    numbered exports preserve previous PDFs in the same directory.
    """
    import json
    from .pdf_diagnostics import usable_pdf, pending_marker
    folder = Path(folder)
    if name is None:
        record = folder / 'registro.json'
        if not record.is_file():
            return folder / 'cadastro.pdf'
        name = json.loads(record.read_text(encoding='utf-8'))['name']
    base = safe_name(name)
    candidates = [folder / (base + '.pdf')]
    index = 2
    while candidates[-1].exists() or pending_marker(candidates[-1]).exists():
        candidates.append(folder / f'{base} ({index}).pdf')
        index += 1
    if new:
        return candidates[-1]
    for path in reversed(candidates[:-1]):
        if usable_pdf(path):
            return path
    # Compatibility with outputs generated by older versions.
    legacy = folder / 'cadastro.pdf'
    return legacy if usable_pdf(legacy) else candidates[0]
